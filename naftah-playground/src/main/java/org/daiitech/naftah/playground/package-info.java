/**
 * Provides the browser-based playground for the Naftah programming language.
 *
 * <p>This package contains the classes responsible for executing Naftah code
 * within a web browser using CheerpJ. It serves as the integration layer
 * between the Naftah runtime, the Java execution environment, and the
 * surrounding JavaScript application.
 *
 * <p>The playground enables users to:
 * <ul>
 * <li>Execute Naftah code interactively in the browser.</li>
 * <li>Communicate between Java and JavaScript through native bridge methods.</li>
 * <li>Display execution results, diagnostics, and runtime output in a web interface.</li>
 * <li>Run Naftah programs without requiring a local Java installation.</li>
 * </ul>
 *
 * <p>This package is intended for the online playground and demonstration
 * environment and is not considered part of the public Naftah runtime API.
 *
 * @author Chakib Daii
 */
package org.daiitech.naftah.playground;
